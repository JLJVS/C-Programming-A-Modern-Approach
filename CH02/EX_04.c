#include <stdio.h>

int main(void)
{
    int a, b, c;
    float x, y, z;
    
    printf("ints: \n");
    printf("a: %d\n", a);
    printf("b: %d\n", b);
    printf("c: %d\n", c);

    printf("floats: \n");
    printf("x: %f\n", x);
    printf("y: %f\n", y);
    printf("z: %f\n", z);


    return 0;
}